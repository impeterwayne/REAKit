#!/usr/bin/env python3
"""PreToolUse gate: protect generated reverse-engineering artifacts from hand edits.

A reverse-engineering workspace is full of files that are *regenerated* on the next
tool run, not authored: JADX-decompiled sources under `jadx_src/`, extracted native
libraries and their Ghidra exports under `native/`, downloaded packages under `apks/`,
and pulled sandbox state under `runtime/`. Editing them in place is a trap -- the edit
looks like progress, then `rea decode` / `rea native extract` / `rea pull` silently
overwrites it, and any finding that lived only in that edit is gone.

So this denies *writes* into the generated regions of a target workspace and points the
analyst at the durable place instead: a note under `findings/` or `docs/`, or a patch
script the pipeline can re-apply. Reads and greps over those regions are never touched --
you analyse the decompilation freely, you just do not treat it as a source tree.

Why PreToolUse and not PostToolUse: the PostToolUse payload carries no `toolCall`, so it
cannot know which file was written. PreToolUse carries `toolCall.args`, and can `deny`
with a reason the model can act on *before* the clobbered write lands.

Fail-open by design. Any internal error, unknown argument shape, or non-generated target
yields PASS_DECISION -- a buggy gate that blocks work is worse than one that misses a case.

Usage:
  hooks/artifact_guard.py            # hook mode: JSON payload on stdin, verdict on stdout
  hooks/artifact_guard.py --self-test
  hooks/artifact_guard.py --status
  hooks/artifact_guard.py --off / --on
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

PASS_DECISION = "ask"  # never "allow": that would silently auto-approve every write

HOOKS_DIR = Path(__file__).resolve().parent
STATE_DIR = HOOKS_DIR.parent / "state" / "artifact_guard"
OFF_SWITCH = STATE_DIR / "off"

# A path segment matching one of these is generated by a `rea` command and owned by it.
# Matched as a whole path component so `findings/jadx_notes.md` is never caught.
GENERATED_SEGMENTS = {
    "jadx_src",   # rea decode  -> JADX output
    "native",     # rea native extract / import -> .so + Ghidra exports
    "apks",       # rea download -> acquired packages
    "runtime",    # rea pull    -> sandbox internal/external state
    "frida",      # rea frida   -> dynamic/frida probe logs
}

# Suffixes that are always acquired binaries, wherever they sit. Writing one by hand is
# always a mistake: it is either a download artifact or a build output of the toolchain.
GENERATED_SUFFIXES = {".apk", ".xapk", ".apks", ".dex", ".so", ".odex", ".vdex"}

# A note or patch is the sanctioned output even when it sits beside generated files.
EXEMPT_SEGMENTS = {"findings", "docs", "notes", "patches"}


def is_generated(path: str) -> bool:
    parts = [p for p in re.split(r"[\\/]+", path) if p not in ("", ".", "..")]
    if any(seg in EXEMPT_SEGMENTS for seg in parts):
        return False
    if Path(path).suffix.lower() in GENERATED_SUFFIXES:
        return True
    return any(seg in GENERATED_SEGMENTS for seg in parts)


def extract_target(args):
    """Best-effort target path from tool args. Mirrors write_guard.extract_target."""
    if not isinstance(args, dict):
        return None
    for key, val in args.items():
        if not isinstance(val, str):
            continue
        k = key.lower()
        if "targetfile" in k or k.endswith("path") or k == "file":
            return val
    return None


def switched_off() -> bool:
    return OFF_SWITCH.exists()


def hook_mode() -> None:
    verdict = {"decision": PASS_DECISION}
    try:
        if switched_off():
            print(json.dumps(verdict))
            return
        payload = json.loads(sys.stdin.read() or "{}")
        call = payload.get("toolCall") or {}
        path = extract_target(call.get("args"))

        if path and is_generated(path):
            verdict = {
                "decision": "deny",
                "reason": (
                    f"{Path(path).name} lives in generated tool output; a hand edit here is "
                    "lost the next time `rea decode` / `rea native extract` / `rea pull` runs.\n"
                    "Put the result where it survives:\n"
                    "  - a note under findings/ or docs/ (what you found, with the address/line)\n"
                    "  - a patch or Frida/hook script the pipeline can re-apply\n"
                    "Reading and grepping these files is fine -- only in-place edits are blocked.\n"
                    "To lift this for the session: run "
                    "`python .agents/hooks/artifact_guard.py --off`."
                ),
            }
    except Exception as exc:  # fail open: never block work over our own bug
        print(f"artifact_guard: {type(exc).__name__}: {exc}", file=sys.stderr)

    print(json.dumps(verdict))


def set_switch(off: bool) -> None:
    STATE_DIR.mkdir(parents=True, exist_ok=True)
    if off:
        OFF_SWITCH.write_text("off\n", encoding="utf-8")
        print("artifact_guard: OFF for this workspace (writes into generated dirs pass)")
    else:
        OFF_SWITCH.unlink(missing_ok=True)
        print("artifact_guard: ON")


def self_test() -> int:
    failures = 0

    def check(name, cond):
        nonlocal failures
        print(f"  {'ok  ' if cond else 'FAIL'} {name}")
        if not cond:
            failures += 1

    for path, expected in [
        ("workspaces/com.app/jadx_src/com/app/Api.java", True),
        ("workspaces/com.app/native/arm64-v8a/libfoo.so", True),
        ("workspaces/com.app/apks/base.apk", True),
        ("workspaces/com.app/runtime/internal/databases/app.db", True),
        ("downloads/anything.dex", True),
        ("findings/api-auth.md", False),
        ("workspaces/com.app/findings/jadx_notes.md", False),
        ("docs/analysis/native.md", False),
        ("scripts/deobfuscate.py", False),
        ("patches/root-bypass.js", False),
    ]:
        check(f"is_generated({path}) is {expected}", is_generated(path) is expected)

    deny = _verdict_for("workspaces/com.app/jadx_src/A.java")
    check("write into jadx_src is denied", deny.get("decision") == "deny")
    check("denial points at findings/", "findings/" in (deny.get("reason") or ""))

    ok = _verdict_for("findings/report.md")
    check("write to findings passes", ok.get("decision") == PASS_DECISION)

    ok2 = _verdict_for(None)
    check("unknown path shape passes", ok2.get("decision") == PASS_DECISION)

    print("\nall self-tests passed" if not failures else f"\n{failures} failure(s)")
    return 1 if failures else 0


def _verdict_for(path):
    """Exercise the deny/pass branch without spawning a subprocess."""
    if path is not None and is_generated(path):
        return {"decision": "deny", "reason": "generated ... findings/ ..."}
    return {"decision": PASS_DECISION}


def main(argv) -> int:
    if "--self-test" in argv:
        return self_test()
    if "--off" in argv:
        set_switch(True)
        return 0
    if "--on" in argv:
        set_switch(False)
        return 0
    if "--status" in argv:
        print(f"artifact_guard: {'OFF' if switched_off() else 'ON'}  state={STATE_DIR}")
        return 0
    hook_mode()
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
